"""
report.py — the Final Report with Business Recommendations.

Sections: executive summary · data quality · key findings · answers to the questions asked ·
recommendations · next steps. With an AI key the summary and recommendations are written
by the model from the computed facts (it is told to use only those numbers); without a key
they are generated by rules from the same facts.
"""

from __future__ import annotations

from datetime import datetime

import pandas as pd

from .llm import LLM, MockLLM
from .quality import grade, quality_scores
from .stats import analyze, column_roles, monthly_trend

REC_SYSTEM = """You are a senior business analyst. From the FACTS only (never invent numbers),
write JSON: {"summary": "<3 sentences for an executive>",
"recommendations": [{"title": "...", "why": "<evidence with numbers from FACTS>", "action": "<concrete next step>",
"priority": "High|Medium|Low"}]} with 4-6 recommendations ordered by priority."""


def trend_change(df: pd.DataFrame) -> list[str]:
    """Compare the last 3 complete months with the 3 before them, for each date column."""
    notes = []
    for dc in column_roles(df)["datetime"]:
        t = monthly_trend(df, dc)
        if len(t) >= 7:
            last, prev = t.value.iloc[-4:-1].mean(), t.value.iloc[-7:-4].mean()
            if prev:
                ch = 100 * (last - prev) / prev
                if abs(ch) >= 10:
                    notes.append(f"Monthly rows by `{dc}` {'fell' if ch < 0 else 'rose'} {abs(ch):.0f}% "
                                 f"(last 3 full months vs the 3 before).")
    return notes


def collect_facts(results, relationships, answers=()) -> list[str]:
    facts = []
    for t, r in results.items():
        b, a = quality_scores(r.raw), quality_scores(r.clean)
        facts.append(f"Table {t}: {b['rows']:,} rows → {a['rows']:,}; quality {b['overall']} → {a['overall']}; "
                     f"{b['missing_cells']:,} missing cells, {b['duplicate_rows']:,} duplicate rows, "
                     f"{b['invalid_values']:,} invalid values.")
        facts += analyze(r.clean, t)["insights"][1:]
        facts += trend_change(r.clean)
    if relationships is not None and not relationships.empty:
        for _, x in relationships[relationships.orphan_rows > 0].iterrows():
            facts.append(f"{x.orphan_rows:,} rows in {x.child_table} have a {x.column} that does not exist in "
                         f"{x.parent_table} (e.g. {x.orphan_examples}).")
    for a in answers:
        if not a.error:
            facts.append(f"Q: {a.question} — A: {a.text}")
    return facts


def rule_recommendations(results, relationships) -> list[dict]:
    recs = []
    if relationships is not None and not relationships.empty:
        bad = relationships[relationships.orphan_rows > 0]
        for _, x in bad.iterrows():
            recs.append(dict(priority="High", title=f"Fix orphan {x.column} values in {x.child_table}",
                             why=f"{x.orphan_rows:,} rows point to a {x.column} that isn't in {x.parent_table} "
                                 f"(e.g. {x.orphan_examples}); revenue or activity can't be attributed.",
                             action=f"Add a foreign-key check in the source system and correct the {x.orphan_rows} rows."))
    for t, r in results.items():
        b = quality_scores(r.raw)
        if b["duplicate_rows"]:
            recs.append(dict(priority="High", title=f"Stop duplicate records in {t}",
                             why=f"{b['duplicate_rows']:,} exact duplicate rows inflated counts and totals.",
                             action="Enforce a unique key at data entry / in the export job."))
        if b["invalid_values"]:
            recs.append(dict(priority="Medium", title=f"Validate numeric inputs in {t}",
                             why=f"{b['invalid_values']:,} impossible values (e.g. negative quantities) were found.",
                             action="Add range checks (>= 0) to the form or ETL step."))
        miss = r.profile_before.sort_values("missing_pct", ascending=False).iloc[0]
        if miss.missing_pct >= 1:
            recs.append(dict(priority="Medium", title=f"Make `{miss.column}` required in {t}",
                             why=f"{miss.missing_pct}% of rows were missing `{miss.column}` and had to be filled.",
                             action="Make the field mandatory and monitor completeness weekly."))
        for x in r.log:
            if x["action"].startswith("Possible duplicate labels"):
                recs.append(dict(priority="Medium", title=f"Standardise `{x['column']}` labels in {t}",
                                 why=x["action"].replace(" — flagged for review", "") + f" ({x['rows_affected']} rows).",
                                 action="Merge the variants and use a drop-down list instead of free text at entry."))
        for n in trend_change(r.clean):
            if "fell" in n:
                recs.append(dict(priority="High", title=f"Investigate the drop in {t}", why=n,
                                 action="Break the drop down by channel, region and product to find its source."))
    recs.append(dict(priority="Low", title="Automate this check", why="All issues above were found automatically.",
                     action="Run the agent on every new export (n8n schedule) and email the quality report."))
    order = {"High": 0, "Medium": 1, "Low": 2}
    return sorted(recs, key=lambda x: order[x["priority"]])[:6]


def build_report(results, relationships, answers, llm: LLM) -> str:
    facts = collect_facts(results, relationships, answers)
    summary, recs = None, None
    if not isinstance(llm, MockLLM):
        try:
            out = llm.complete_json(REC_SYSTEM, "FACTS\n- " + "\n- ".join(facts), max_tokens=1800)
            summary, recs = out.get("summary"), out.get("recommendations")
        except Exception:
            pass
    if not recs:
        recs = rule_recommendations(results, relationships)
    if not summary:
        total_rows = sum(len(r.raw) for r in results.values())
        fixes = sum(len(r.log) for r in results.values())
        avg_after = sum(quality_scores(r.clean)["overall"] for r in results.values()) / len(results)
        summary = (f"The agent analysed {len(results)} table(s) with {total_rows:,} rows and applied {fixes} "
                   f"documented cleaning steps, bringing average data quality to {avg_after:.1f}/100. "
                   f"{recs[0]['title']} is the most urgent action.")

    out = ["# Final Analysis Report", f"_AI-Powered Data Analyst Agent · {datetime.now():%Y-%m-%d} · "
                                      f"AI: {'offline rules' if isinstance(llm, MockLLM) else llm.name}_", "", "## Executive summary", summary, "",
           "## Data quality", "| Table | Rows before → after | Score before → after |", "|---|---|---|"]
    for t, r in results.items():
        b, a = quality_scores(r.raw), quality_scores(r.clean)
        out.append(f"| {t} | {b['rows']:,} → {a['rows']:,} | {b['overall']} ({grade(b['overall'])}) → "
                   f"{a['overall']} ({grade(a['overall'])}) |")
    out += ["", "## Key findings"] + [f"- {f}" for f in facts if not f.startswith(("Table ", "Q: "))][:12]
    if answers:
        out += ["", "## Questions answered"]
        for a in answers:
            out += [f"**{a.question}**", "", a.text or a.error, "", "```sql", a.sql, "```", ""]
    out += ["## Recommendations", "| Priority | Recommendation | Evidence | Action |", "|---|---|---|---|"]
    for r in recs:
        out.append(f"| {r.get('priority', '')} | {r.get('title', '')} | {r.get('why', '')} | {r.get('action', '')} |")
    return "\n".join(out)
