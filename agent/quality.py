"""
quality.py — Data Quality scoring, cross-table checks and the Data Quality Report.

Quality score (0-100) = average of four dimensions
    Completeness  share of cells that are not missing
    Uniqueness    share of rows that are not duplicates (row or key)
    Validity      share of numeric cells that are not impossible (e.g. negative quantity)
    Consistency   share of cells whose type matches their column (no numbers-as-text, dates-as-text)
"""

from __future__ import annotations

from datetime import datetime

import pandas as pd

from . import profiler as P
from .cleaner import CleanResult


def quality_scores(df: pd.DataFrame, prof: pd.DataFrame | None = None) -> dict:
    prof = P.profile_table(df) if prof is None else prof
    n, m = df.shape
    cells = max(n * m, 1)
    missing = int(prof.missing.sum())
    completeness = 100 * (1 - missing / cells)

    dup_rows = int(df.duplicated().sum())
    key = P.find_key_column(df, prof)
    key_dups = int((df[key].notna() & df.duplicated(subset=[key])).sum()) if key else 0
    uniqueness = 100 * (1 - (dup_rows + max(key_dups - dup_rows, 0)) / max(n, 1))

    invalid = 0
    numeric_cells = 0
    for _, r in prof.iterrows():
        if r.semantic_type in ("numeric", "numeric_text"):
            numeric_cells += n
            if P.non_negative_expected(P._snake(r.column)):
                invalid += int(r.negatives or 0)
    validity = 100 * (1 - invalid / max(numeric_cells, 1))

    mistyped = int(prof.semantic_type.isin(["numeric_text", "date_text"]).sum())
    consistency = 100 * (1 - mistyped / max(m, 1))

    overall = (completeness + uniqueness + validity + consistency) / 4
    return dict(overall=round(overall, 1), completeness=round(completeness, 1), uniqueness=round(uniqueness, 1),
                validity=round(validity, 2), consistency=round(consistency, 1),
                rows=n, columns=m, missing_cells=missing, duplicate_rows=dup_rows,
                duplicate_keys=key_dups, invalid_values=invalid, mistyped_columns=mistyped, key_column=key)


def grade(score: float) -> str:
    return "A" if score >= 95 else "B" if score >= 85 else "C" if score >= 70 else "D"


def find_relationships(results: dict[str, CleanResult]) -> pd.DataFrame:
    """Find foreign keys: a column in one table that matches the primary key of another,
    and count orphans (values that don't exist in the parent table)."""
    rows = []
    keys = {t: r.key_column for t, r in results.items() if r.key_column}
    for parent, pk in keys.items():
        parent_vals = set(results[parent].clean[pk].dropna().unique())
        for child, res in results.items():
            if child == parent or pk not in res.clean.columns:
                continue
            col = res.clean[pk].dropna()
            orphans = ~col.isin(parent_vals)
            rows.append(dict(child_table=child, column=pk, parent_table=parent,
                             child_rows=len(col), orphan_rows=int(orphans.sum()),
                             orphan_pct=round(100 * orphans.mean(), 2) if len(col) else 0.0,
                             orphan_examples=", ".join(map(str, col[orphans].unique()[:5]))))
    return pd.DataFrame(rows, columns=["child_table", "column", "parent_table", "child_rows",
                                       "orphan_rows", "orphan_pct", "orphan_examples"])


def _md_table(df: pd.DataFrame) -> str:
    if df is None or df.empty:
        return "_none_"
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else (f"{v:,}" if isinstance(v, int) else str(v))
                                        for v in r.values) + " |")
    return "\n".join(lines)


def quality_report_md(results: dict[str, CleanResult], relationships: pd.DataFrame | None = None) -> str:
    """Human-readable Data Quality Report (Markdown)."""
    out = [f"# Data Quality Report",
           f"_Generated by the AI-Powered Data Analyst Agent · {datetime.now():%Y-%m-%d %H:%M}_", ""]
    summary = []
    for t, r in results.items():
        b, a = quality_scores(r.raw, r.profile_before), quality_scores(r.clean, r.profile_after)
        summary.append(dict(table=t, rows_before=b["rows"], rows_after=a["rows"],
                            score_before=f"{b['overall']} ({grade(b['overall'])})",
                            score_after=f"{a['overall']} ({grade(a['overall'])})",
                            missing_before=b["missing_cells"], duplicates_before=b["duplicate_rows"],
                            fixes=len(r.log)))
    out += ["## 1. Summary", _md_table(pd.DataFrame(summary)), ""]

    if relationships is not None and not relationships.empty:
        out += ["## 2. Relationships between tables",
                "Foreign keys found automatically. *Orphans* are IDs that don't exist in the parent table.",
                _md_table(relationships), ""]

    for i, (t, r) in enumerate(results.items(), start=1):
        b = quality_scores(r.raw, r.profile_before)
        a = quality_scores(r.clean, r.profile_after)
        out += [f"## Table: `{t}`",
                f"Key column: **{r.key_column or 'none found'}** · "
                f"{b['rows']:,} rows → {a['rows']:,} rows · quality {b['overall']} → **{a['overall']}**", "",
                "| Dimension | Before | After |", "|---|---|---|"]
        for dim in ["completeness", "uniqueness", "validity", "consistency"]:
            out.append(f"| {dim.title()} | {b[dim]} | {a[dim]} |")
        issues = r.profile_before[(r.profile_before.missing > 0) | (r.profile_before.negatives > 0) |
                                  (r.profile_before.outliers > 0) |
                                  r.profile_before.semantic_type.isin(["numeric_text", "date_text"])]
        out += ["", "**Issues found**", _md_table(issues[["column", "semantic_type", "missing", "missing_pct",
                                                           "negatives", "outliers"]]),
                "", "**What the agent did**", _md_table(r.log_df), ""]
    return "\n".join(out)
